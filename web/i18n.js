// Fallback to English for missing translations
function t(key, lang, values={}) {
    const alias=Object.keys(translations.en).find(name=>translations.en[name]===key);
    const text=copy[lang]?.[key] ?? translations[lang]?.[key] ?? (alias?translations[lang]?.[alias]:undefined) ?? translations.en[key] ?? key;
    return text.replace(/\{(\w+)\}/gu,(match,name)=>Object.hasOwn(values,name)?String(values[name]):match);
}
export function uiText(key,values={}){return t(key,document.documentElement.lang,values);}

export function applyTranslations(lang) {
    // Update all elements with data-i18n attribute
    document.querySelectorAll('[data-i18n]').forEach(el => {
        // Skip elements that have element children (e.g., buttons with SVG icons)
        if(el.querySelector('*'))return;
        const key = el.getAttribute('data-i18n');
        el.textContent = t(key, lang);
    });

    // Update all elements with data-i18n-placeholder attribute
    document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
        const key = el.getAttribute('data-i18n-placeholder');
        el.placeholder = t(key, lang);
    });

    // Update all elements with data-i18n-title attribute
    document.querySelectorAll('[data-i18n-title]').forEach(el => {
        const key = el.getAttribute('data-i18n-title');
        el.title = t(key, lang);
    });
    document.querySelectorAll('[data-i18n-aria-label]').forEach(el=>el.setAttribute('aria-label',t(el.dataset.i18nAriaLabel,lang)));

    // Update document language
    document.documentElement.lang = lang;
}

export { t };

export function applyWorkspaceTranslations(language){
    applyTranslations(language);
    const groups={connection:'Model connection',recovery:'Workspace & recovery',appearance:'Appearance',advanced:'Advanced',plugins:'Plugins'};
    document.querySelectorAll('[data-settings-tab]').forEach(element=>element.textContent=t(groups[element.dataset.settingsTab]??element.dataset.settingsTab,language));
}
