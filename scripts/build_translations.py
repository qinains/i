#!/usr/bin/env python3
"""Validate source catalogs and generate dependency-free browser translations."""
import argparse
from collections import Counter
import json
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parent.parent
PLACEHOLDERS = re.compile(r"\{(?:[a-zA-Z_]\w*|\d*)\}")
URLS = re.compile(r"https?://[A-Za-z0-9._~:/?#\[\]@!$&()*+,;=%-]+")
RUNTIME = r'''
export const languageCodes=languageOptions.map(item=>item.code);
export function detectLanguage(preferences=[],supported=languageCodes){
    for(const preference of preferences??[]){
        if(typeof preference!=='string')continue;
        const tag=preference.replaceAll('_','-').toLowerCase(),parts=tag.split('-');
        const exact=supported.find(code=>code.toLowerCase()===tag);if(exact)return exact;
        const candidate=parts[0]==='zh'
            ? parts.includes('hans')?'zh-CN':parts.includes('hant')||parts.some(part=>['tw','hk','mo'].includes(part))?'zh-TW':'zh-CN'
            : supported.find(code=>code.toLowerCase()===parts[0]);
        if(supported.includes(candidate))return candidate;
    }
    return supported.includes('en')?'en':supported[0]??'en';
}
export function resolveLanguage(saved,preferences=[]){return languageCodes.includes(saved)?saved:detectLanguage(preferences);}
export function languageDirection(code){return languageOptions.find(item=>item.code===code)?.dir??'ltr';}
export function populateLanguageSelect(select){
    const previous=select.value;
    select.replaceChildren(...languageOptions.map(item=>{
        const option=select.ownerDocument.createElement('option');option.value=item.code;option.textContent=item.name;option.lang=item.code;option.dir=item.dir;return option;
    }));
    if(languageCodes.includes(previous))select.value=previous;
}
'''


def read_json(path):
    def unique(items):
        result = {}
        for key, value in items:
            if key in result:
                raise ValueError(f"{path}: duplicate key {key}")
            result[key] = value
        return result
    return json.loads(path.read_text(encoding="utf-8"), object_pairs_hook=unique)


def urls(text):
    return sorted(match.rstrip(".,;:)]，。；：）") for match in URLS.findall(text))


def catalog(path, base):
    messages = read_json(path)
    if not isinstance(messages, dict) or messages.keys() != base.keys():
        raise ValueError(f"{path}: catalog keys differ from English")
    for key, text in messages.items():
        if not isinstance(text, str) or not text.strip():
            raise ValueError(f"{path}: empty or invalid translation for {key}")
        if re.search(r"[\u202a-\u202e\u2066-\u2069]", text):
            raise ValueError(f"{path}: explicit bidi controls are not allowed")
        if Counter(PLACEHOLDERS.findall(text)) != Counter(PLACEHOLDERS.findall(base[key])):
            raise ValueError(f"{path}: placeholder mismatch for {key}")
        if urls(text) != urls(base[key]):
            raise ValueError(f"{path}: API URL mismatch for {key}")
    return messages


def js(value):
    return json.dumps(value, ensure_ascii=False, separators=(",", ":")).replace("\u2028", "\\u2028").replace("\u2029", "\\u2029")


def outputs(root=ROOT):
    registry = read_json(root / "locales/languages.json")
    codes = [item["code"] for item in registry]
    if not registry or "en" not in codes or len(codes) != len(set(codes)):
        raise ValueError("Invalid language registry")
    for item in registry:
        if not re.fullmatch(r"[a-z]{2,3}(?:-[A-Z]{2})?", item["code"]) or item["dir"] not in {"ltr", "rtl"} or not item["name"].strip():
            raise ValueError("Invalid language metadata")
    header = "// Generated by scripts/build_translations.py; edit locales/ sources instead.\n"
    metadata = header + "export const languageOptions=" + js(registry) + ";\n" + RUNTIME
    result = {"web/languages.js": metadata, "site/assets/languages.js": metadata}
    for area, export in [("web", "copy"), ("site", "catalogs")]:
        directory = root / "locales" / area
        base = read_json(directory / "en.json")
        keys = list(base)
        rows = {code: [messages[key] for key in keys] for code in codes for messages in [catalog(directory / f"{code}.json", base)]}
        result[f'{"web" if area == "web" else "site/assets"}/translations.js'] = (
            header + "const keys=" + js(keys) + ";\nconst rows=" + js(rows) + ";\n"
            + f"export const {export}=Object.fromEntries(Object.entries(rows).map(([code,values])=>[code,Object.fromEntries(keys.map((key,index)=>[key,values[index]]))]));\n"
        )
    native = read_json(root / "locales/en.json")
    for code in codes:
        catalog(root / f"locales/{code}.json", native)
    result["src/locales_generated.rs"] = (
        "// Generated by scripts/build_translations.py; edit locales/ sources instead.\n"
        + 'pub const LOCALES: &[(&str, &str)] = &[\n'
        + "".join(f'    ("{code}", include_str!("../locales/{code}.json")),\n' for code in codes) + "];\n"
    )
    return result


def generate(root=ROOT, check=False):
    for name, content in outputs(root).items():
        path = root / name
        if check:
            if not path.is_file() or path.read_text(encoding="utf-8") != content:
                raise ValueError(f"Generated translation file is stale: {name}")
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content, encoding="utf-8", newline="\n")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    try:
        generate(check=args.check)
    except (ValueError, KeyError, OSError) as error:
        parser.exit(1, f"Translation validation failed: {error}\n")
    print("Translation catalogs verified" if args.check else "Translation modules generated")
