use crate::{read_json, text, write};
use anyhow::{Context, Result, ensure};
use regex::Regex;
use serde_json::{Map, Value};
use std::{
    collections::{BTreeMap, BTreeSet},
    fs,
    path::Path,
    sync::LazyLock,
};
static PLACEHOLDERS: LazyLock<Regex> = LazyLock::new(|| Regex::new(r"\{(?:[a-zA-Z_]\w*|\d*)\}").unwrap());
static URLS: LazyLock<Regex> = LazyLock::new(|| Regex::new(r"https?://[A-Za-z0-9._~:/?#\[\]@!$&()*+,;=%-]+").unwrap());
fn js(value: &Value) -> String {
    serde_json::to_string(value).unwrap().replace('\u{2028}', "\\u2028").replace('\u{2029}', "\\u2029")
}
fn matches(pattern: &Regex, text: &str) -> Vec<String> {
    let mut result = pattern.find_iter(text).map(|m| m.as_str().to_string()).collect::<Vec<_>>();
    result.sort();
    result
}
fn urls(text: &str) -> Vec<String> {
    let mut result = matches(&URLS, text)
        .into_iter()
        .map(|s| s.trim_end_matches(['.', ',', ';', ':', ')', ']', '，', '。', '；', '：', '）']).to_owned())
        .collect::<Vec<_>>();
    result.sort();
    result
}
fn catalog(path: &Path, base: &Value) -> Result<Value> {
    let value = read_json(path)?;
    let messages = value.as_object().context("catalog must be an object")?;
    let english = base.as_object().context("English catalog must be an object")?;
    ensure!(
        messages.len() == english.len() && messages.keys().all(|key| english.contains_key(key)),
        "{}: catalog keys differ from English",
        path.display()
    );
    for (key, value) in messages {
        let translation = value.as_str().context("translation must be a string")?;
        let original = english[key].as_str().context("English translation must be a string")?;
        ensure!(!translation.trim().is_empty(), "empty translation: {key}");
        ensure!(
            !translation
                .chars()
                .any(|c| ('\u{202a}'..='\u{202e}').contains(&c) || ('\u{2066}'..='\u{2069}').contains(&c)),
            "explicit bidi controls: {key}"
        );
        ensure!(matches(&PLACEHOLDERS, translation) == matches(&PLACEHOLDERS, original), "placeholder mismatch: {key}");
        ensure!(urls(translation) == urls(original), "API URL mismatch: {key}");
    }
    Ok(value)
}
pub fn outputs(root: &Path) -> Result<BTreeMap<String, String>> {
    let registry = read_json(&root.join("locales/languages.json"))?;
    let languages = registry.as_array().context("invalid language registry")?;
    let mut codes = vec![];
    let mut seen = BTreeSet::new();
    let pattern = Regex::new(r"^[a-z]{2,3}(?:-[A-Z]{2})?$")?;
    for item in languages {
        let code = text(item, "code")?;
        ensure!(
            pattern.is_match(code)
                && seen.insert(code.to_owned())
                && matches!(text(item, "dir")?, "ltr" | "rtl")
                && !text(item, "name")?.trim().is_empty(),
            "invalid language metadata"
        );
        codes.push(code.to_owned());
    }
    ensure!(seen.contains("en"), "invalid language registry");
    let header = "// Generated by tools/site-tool; edit locales/ sources instead.\n";
    let metadata =
        format!("{header}export const languageOptions={};\n{}", js(&registry), include_str!("language-runtime.js"));
    let mut result =
        BTreeMap::from([("web/languages.js".into(), metadata.clone()), ("site/assets/languages.js".into(), metadata)]);
    for (area, export, destination) in [("web", "copy", "web"), ("site", "catalogs", "site/assets")] {
        let directory = root.join("locales").join(area);
        let base = read_json(&directory.join("en.json"))?;
        let keys = base.as_object().context("English catalog object")?.keys().cloned().collect::<Vec<_>>();
        let mut rows = Map::new();
        for code in &codes {
            let messages = catalog(&directory.join(format!("{code}.json")), &base)?;
            rows.insert(code.clone(), keys.iter().map(|key| messages[key].clone()).collect::<Vec<_>>().into());
        }
        result.insert(format!("{destination}/translations.js"),format!("{header}const keys={};\nconst rows={};\nexport const {export}=Object.fromEntries(Object.entries(rows).map(([code,values])=>[code,Object.fromEntries(keys.map((key,index)=>[key,values[index]]))]));\n",js(&serde_json::to_value(keys)?),js(&rows.into())));
    }
    let base = read_json(&root.join("locales/en.json"))?;
    for code in &codes {
        catalog(&root.join(format!("locales/{code}.json")), &base)?;
    }
    let rows = codes
        .iter()
        .map(|code| format!("    (\"{code}\", include_str!(\"../locales/{code}.json\")),\n"))
        .collect::<String>();
    result.insert(
        "src/locales_generated.rs".into(),
        format!("{header}pub const LOCALES: &[(&str, &str)] = &[\n{rows}];\n"),
    );
    Ok(result)
}
pub fn generate(root: &Path, check: bool) -> Result<()> {
    for (name, content) in outputs(root)? {
        let path = root.join(&name);
        if check {
            ensure!(
                fs::read_to_string(&path).ok().as_deref() == Some(&content),
                "Generated translation file is stale: {name}"
            );
        } else {
            write(&path, content)?;
        }
    }
    Ok(())
}
